#!/usr/bin/env python
"""Prove a trained countermeasure checkpoint actually loads in the backend.

This is the last mile of the experiment: a checkpoint that scores well in
`reports/` is not the same thing as a countermeasure that is in the request
path. `vanirakshak/detectors/cm_aasist.py` is an intentionally empty landing
zone -- `try_create()` returns ``None`` until `VR_CM_AASIST_WEIGHTS` points at
real weights, and the pipeline then silently falls back to the stub while
reporting ``aasist_missing_weights``. A deployment can therefore look correct
and be running the heuristic.

So this script does not re-implement the backend's rules, which would drift. It
**imports the backend module** and calls its own `_validate_checkpoint`, then
(optionally) constructs the real detector and scores a real wav with it.

Checks, in order:

1. the checkpoint satisfies the backend's schema (exactly its rules);
2. provenance is printed -- init_weights, seed, augmentation, layer index,
   best epoch -- because "which model is this?" is a deployment question;
3. the exact env block to deploy is emitted;
4. with ``--live``: the real detector is constructed and actually scores audio,
   and the script fails unless ``name != "aasist_missing_weights"``. That string
   is the difference between "the trained model is in the loop" and "the stub
   is still deciding".

Usage:
    python scripts/wire_cm_into_backend.py --checkpoint data/cm_scratch_S42.pt
    python scripts/wire_cm_into_backend.py --checkpoint data/cm_scratch_S42.pt \
        --live --audio C:/VaniRakshak/test_audio/hindi_sample.wav \
        --out handoff/cm_backend_env_2026-09-16.env
"""

from __future__ import annotations

import argparse
import importlib
import json
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_BACKEND_ROOT = Path(r"C:\VaniRakshak\vanirakshak-backend")
DEFAULT_AUDIO = Path(r"C:\VaniRakshak\test_audio\hindi_sample.wav")

SAMPLE_RATE = 16000
WINDOW_S = 4.0


def load_backend_detector(backend_root: Path):
    """Import the backend's own detector module so its rules cannot drift."""
    if not backend_root.is_dir():
        raise SystemExit(
            f"backend root not found: {backend_root}\n"
            f"Pass --backend-root pointing at the checkout that contains "
            f"vanirakshak/detectors/cm_aasist.py")
    if str(backend_root) not in sys.path:
        sys.path.insert(0, str(backend_root))
    try:
        return importlib.import_module("vanirakshak.detectors.cm_aasist")
    except Exception as exc:  # noqa: BLE001 - report, never silently pass
        raise SystemExit(f"cannot import the backend detector module: "
                         f"{type(exc).__name__}: {exc}") from exc


def validate(cm, ckpt_path: Path) -> dict:
    import torch

    ckpt = torch.load(str(ckpt_path), map_location="cpu")
    cm._validate_checkpoint(ckpt, ckpt_path)   # the backend's own rules
    return ckpt


def env_block(ckpt_path: Path, extra: dict | None = None,
              has_calibration: bool = False) -> str:
    # The closing note used to assert unconditionally that "this head ships no
    # calibration block". That was true for the early checkpoints and is false
    # for any checkpoint that has been through fit_cm_calibration.py, so state
    # it per-checkpoint rather than as boilerplate.
    if has_calibration:
        closing = [
            "# This checkpoint DOES carry a Platt calibration block, so its",
            "# scores are calibrated. The fusion weights w_cm / w_asv are still",
            "# fitted to the OLD head's LLR distribution -- calibration changes",
            "# the LLR scale, so re-fit them against THIS head before shipping",
            "# (see the integration map).",
        ]
    else:
        closing = [
            "# The fusion weights are still fitted to the OLD head's LLR",
            "# distribution, and this head ships no calibration block, so its",
            "# scores are raw and uncalibrated. Run fit_cm_calibration.py on it,",
            "# then re-fit the fusion weights against this head before shipping",
            "# (see the integration map).",
        ]
    lines = [
        "# Generated by scripts/wire_cm_into_backend.py",
        f"# checkpoint: {ckpt_path}",
        "export VR_CM_BACKEND=aasist",
        f"export VR_CM_AASIST_WEIGHTS={ckpt_path}",
        "# Deliberately NOT exporting VR_FUSION_W_CM / VR_FUSION_W_ASV.",
        "# config.py's _REAL_BACKEND_OVERRIDES already supplies w_cm=1.5 and",
        "# w_asv=2.0 whenever a real backend is active, and that preset exists",
        "# precisely because the stub-era w_cm=2.4 'pushed genuine real clips",
        "# into CHALLENGE' (config.py:126). An explicit env var WINS over the",
        "# preset (config.py:229), so exporting them here would re-introduce",
        "# exactly the false alarm the preset was written to remove.",
        "#",
        "# Measured on data/demo with this checkpoint: w_cm=2.4 -> demo_01",
        "# (genuine) risk 43.2 CHALLENGE, demo_03 BLOCK; with the preset's 1.5",
        "# -> demo_01 38.3, demo_03 66.9 CHALLENGE. The preset is the better",
        "# block on every clip; do not override it.",
        "#",
    ]
    lines += closing
    for k, v in (extra or {}).items():
        lines.append(f"export {k}={v}")
    return "\n".join(lines) + "\n"


def live_score(cm, ckpt_path: Path, audio: Path) -> dict:
    """Construct the real detector and score one utterance with it."""
    os.environ["VR_CM_BACKEND"] = "aasist"
    os.environ["VR_CM_AASIST_WEIGHTS"] = str(ckpt_path)
    det = cm.CMModelAASIST.try_create()
    if det is None:
        raise SystemExit("LIVE FAIL: try_create() returned None -- the backend "
                         "would fall back to the stub for this checkpoint")
    if det.name == "aasist_missing_weights":
        raise SystemExit("LIVE FAIL: detector reports aasist_missing_weights -- "
                         "weights did not load despite passing schema validation")

    import torch
    import torchaudio

    if not audio.is_file():
        raise SystemExit(f"audio not found: {audio}")
    # torchaudio.load() wants TorchCodec, which this box does not have; the
    # resample kernel itself is fine, so decode with soundfile and keep
    # torchaudio only for sample-rate conversion.
    import soundfile as sf

    data, sr = sf.read(str(audio), dtype="float32", always_2d=True)
    wav = torch.from_numpy(data.T)  # (channels, samples)
    if wav.shape[0] > 1:
        wav = wav.mean(dim=0, keepdim=True)
    if sr != SAMPLE_RATE:
        wav = torchaudio.functional.resample(wav, sr, SAMPLE_RATE)
    need = int(SAMPLE_RATE * WINDOW_S)
    if wav.shape[1] < need:      # the checkpoint's training window: pad, don't loop
        wav = torch.nn.functional.pad(wav, (0, need - wav.shape[1]))
    else:
        wav = wav[:, :need]
    pcm = wav.squeeze(0).numpy()

    llr = float(det.score(pcm, SAMPLE_RATE))
    return {
        "name": det.name,
        "dev_eer": det.dev_eer,
        "dev_min_dcf": det.dev_min_dcf,
        "eer_threshold": det.eer_threshold,
        "layer_index": det.layer_index,
        "llr": llr,
        "decides": "genuine-ward" if llr > 0 else "spoof-ward",
        "audio": str(audio),
        "seconds": round(min(pcm.shape[0] / SAMPLE_RATE, WINDOW_S), 3),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__.split("\n")[0],
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--checkpoint", type=Path, required=True)
    ap.add_argument("--backend-root", type=Path, default=DEFAULT_BACKEND_ROOT)
    ap.add_argument("--live", action="store_true",
                    help="Construct the real detector and score --audio with it.")
    ap.add_argument("--audio", type=Path, default=DEFAULT_AUDIO)
    ap.add_argument("--out", type=Path, default=None,
                    help="Write the deployable env block to this file.")
    ap.add_argument("--json-out", type=Path, default=None)
    args = ap.parse_args(argv)

    if not args.checkpoint.is_file():
        raise SystemExit(f"checkpoint not found: {args.checkpoint}")

    cm = load_backend_detector(args.backend_root)
    print("=" * 78)
    print("CM -> BACKEND WIRING CHECK")
    print(f"  checkpoint : {args.checkpoint}")
    print(f"  backend    : {args.backend_root}")
    print("=" * 78)

    try:
        ckpt = validate(cm, args.checkpoint)
    except Exception as exc:  # noqa: BLE001
        print(f"\n  SCHEMA: FAIL -- {type(exc).__name__}: {exc}")
        return 1
    print("\n  SCHEMA: PASS (validated by the backend's own _validate_checkpoint)")

    print("\nProvenance")
    print("-" * 78)
    for key in ("architecture", "frontend", "sample_rate", "window_s",
                "layer_index", "merge_layers", "seed", "best_epoch",
                "init_weights", "unfreeze_top_n", "frontend_dtype",
                "dev_eer", "dev_min_dcf", "eer_threshold"):
        if key in ckpt:
            print(f"  {key:16s} {ckpt[key]}")
    aug = ckpt.get("augmentation")
    if aug:
        print(f"  {'augmentation':16s} {json.dumps(aug)[:110]}")
    cal = ckpt.get("calibration")
    print(f"  {'calibration':16s} "
          f"{'present' if cal else 'ABSENT -- scores are raw LLRs, actDCF will be poor'}")
    if not cal:
        print("                  (calibration cannot move EER or minDCF; it only "
              "fixes the threshold)")

    print("\nDeploy with")
    print("-" * 78)
    block = env_block(args.checkpoint.resolve(), has_calibration=bool(cal))
    print(block, end="")
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(block)
        print(f"  wrote {args.out}")

    live = None
    if args.live:
        print("\nLive smoke test")
        print("-" * 78)
        try:
            live = live_score(cm, args.checkpoint.resolve(), args.audio)
        except SystemExit:
            raise
        except Exception as exc:  # noqa: BLE001
            print(f"  LIVE: FAIL -- {type(exc).__name__}: {exc}")
            print("  (this is an environment gap, e.g. the WavLM cache, not a "
                  "checkpoint problem -- the schema check above still stands)")
            return 1
        for k, v in live.items():
            print(f"  {k:14s} {v}")
        print("\n  LIVE: PASS -- the trained head scored this utterance; "
              "the stub is not deciding.")

    if args.json_out:
        args.json_out.parent.mkdir(parents=True, exist_ok=True)
        args.json_out.write_text(json.dumps({
            "checkpoint": str(args.checkpoint),
            "schema_ok": True,
            "provenance": {k: (str(ckpt[k]) if not isinstance(ckpt[k], (int, float, str, bool, type(None))) else ckpt[k])
                           for k in ckpt if k != "state_dict"},
            "live": live,
        }, indent=2, default=str) + "\n")
        print(f"\nwrote {args.json_out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
